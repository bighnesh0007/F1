const DICTS: Record<Exclude<Lang, "en">, Dict> = { hi, es };

export function translate(lang: Lang, text: string) {
  return lang === "en" ? text : (DICTS[lang]?.[text] ?? text);
}

export function useT() {
  const { settings } = useSettings();
  const lang = settings.language;
  return useCallback((text: string) => translate(lang, text), [lang]);
}

